from enum import Enum
from typing import Any, Dict, List, Optional, Union
from pydantic import BaseModel, Field
from app.schemas.pedagogy import PedagogyDecision


class LessonBlockType(str, Enum):
    # Canonical Backend types (Section 14.2)
    TEXT = "TEXT"
    CODE = "CODE"
    INTERACTIVE = "INTERACTIVE"
    QUIZ = "QUIZ"
    VIDEO = "VIDEO"

    # Lowercase aliases
    text = "text"
    code = "code"
    interactive = "interactive"
    quiz = "quiz"
    video = "video"

    # Sprint 1-3 types (preserved for 100% backward compatibility)
    OBJECTIVE = "objective"
    EXPLANATION = "explanation"
    WORKED_EXAMPLE = "worked_example"
    VISUAL_SPEC = "visual_spec"
    PRACTICE_TASK = "practice_task"

    # Canonical Universal Learning Blocks
    EXAMPLE = "example"
    DIAGRAM = "diagram"
    INTERACTIVE_QUESTION = "interactive_question"
    PRACTICE = "practice"
    ASSESSMENT = "assessment"
    SIMULATION = "simulation"
    VOICE = "voice"


class LessonBlock(BaseModel):
    """A structured learning unit consumed by UniOS Backend and LessonRenderer (Section 14.2)."""

    id: Optional[str] = Field(default=None, description="Unique block ID for checkpoint tracking")
    type: Union[LessonBlockType, str] = Field(
        ...,
        description="Block type: TEXT | CODE | INTERACTIVE | QUIZ | VIDEO or universal types",
    )
    title: Optional[str] = Field(default=None, description="Block title or header")
    content: Optional[Union[str, Dict[str, Any]]] = Field(
        default=None,
        description="Structured content body (markdown prose or structured text)",
    )
    code: Optional[str] = Field(default=None, description="Code content for CODE or INTERACTIVE")
    language: Optional[str] = Field(default=None, description="Programming language identifier (e.g. python)")
    options: Optional[List[str]] = Field(default=None, description="Choice list for QUIZ")
    answer: Optional[str] = Field(default=None, description="Correct choice for QUIZ")
    explanation: Optional[str] = Field(default=None, description="Pedagogical explanation for QUIZ")
    url: Optional[str] = Field(default=None, description="Video or external media URL")
    caption: Optional[str] = Field(default=None, description="Media caption for VIDEO")
    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Structured instructions for renderers or metadata",
    )

    def model_post_init(self, __context):
        # Auto-populate top-level fields from metadata if omitted
        if self.metadata:
            if not self.options and "options" in self.metadata and isinstance(self.metadata["options"], list):
                self.options = self.metadata["options"]
            if not self.answer and "answer" in self.metadata:
                self.answer = str(self.metadata["answer"])
            if not self.explanation and "explanation" in self.metadata:
                self.explanation = str(self.metadata["explanation"])
            if not self.code and "code" in self.metadata:
                self.code = str(self.metadata["code"])
            if not self.language and "language" in self.metadata:
                self.language = str(self.metadata["language"])
            if not self.url and "url" in self.metadata:
                self.url = str(self.metadata["url"])
            if not self.caption and "caption" in self.metadata:
                self.caption = str(self.metadata["caption"])


class AssessmentIntent(BaseModel):
    """Pedagogical assessment intent generated with the lesson (A2-S4-02)."""

    target_concepts: List[str] = Field(default_factory=list)
    assessment_mode: str = Field(
        default="formative",
        description="Assessment mode: formative | diagnostic | summative | viva",
    )
    difficulty: str = Field(default="beginner")
    question_count: int = Field(default=3)
    evaluation_criteria: List[str] = Field(default_factory=list)


class NextLearningAction(BaseModel):
    """Actionable next step recommended by AI/ML-2 based on pedagogy and evidence (A2-S4-04)."""

    action_type: str = Field(
        ...,
        description="Action type: reassessment | practice | next_topic | build_artifact | review",
    )
    target_topic: str
    rationale: str
    urgency: str = Field(default="normal", description="normal | immediate | deferred")


class GeneratedLesson(BaseModel):
    """The final structured lesson generated by AI/ML-2 (Section 14.2 & A2-S4-02)."""

    id: Optional[str] = Field(default=None, description="Unique lesson identifier (lesson_id)")
    title: Optional[str] = Field(default=None, description="Descriptive title of the lesson")
    objective: Optional[str] = Field(default=None, description="Primary learning outcome")
    context_id: Optional[str] = Field(default=None, description="Legacy context identifier")
    request_id: Optional[str] = Field(
        default=None,
        description="Correlation ID for distributed tracing",
    )
    topic: Optional[str] = Field(default="", description="Lesson topic")
    pedagogy_decision: Optional[PedagogyDecision] = Field(
        default=None,
        description="Pedagogical strategy decision",
    )
    prerequisites: List[str] = Field(
        default_factory=list,
        description="Assumed pre-requisite concepts",
    )
    blocks: List[LessonBlock] = Field(
        ..., min_length=1, description="Sequential list of LessonBlock objects"
    )
    assessment_intent: Optional[AssessmentIntent] = Field(
        default=None,
        description="Assessment intent for downstream evaluation and mastery loop",
    )
    next_action: Optional[NextLearningAction] = Field(
        default=None,
        description="Actionable next step recommended by AI/ML-2",
    )

    def model_post_init(self, __context):
        effective_id = self.id or self.context_id or self.request_id or "lesson-001"
        if not self.id:
            self.id = effective_id
        if not self.context_id:
            self.context_id = effective_id
        if not self.request_id:
            self.request_id = effective_id
        if not self.title:
            self.title = f"Mastering {self.topic}" if self.topic else "Structured Interactive Lesson"
        if not self.objective:
            self.objective = f"Understand and implement core concepts of {self.topic}." if self.topic else "Master lesson concepts."

        for idx, blk in enumerate(self.blocks, start=1):
            if not blk.id:
                type_label = str(blk.type).lower().replace("lessonblocktype.", "").replace("_", "-")
                blk.id = f"blk-{idx:02d}-{type_label}"
